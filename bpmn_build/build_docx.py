def P(text="", align=None, size=12, bold=False, italic=False, before=0, after=6,
      line=1.0, name="Times New Roman", color=None):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.line_spacing = line
    if align is not None:
        p.alignment = align
    if text:
        r = p.add_run(text)
        r.font.name = name
        r.font.size = Pt(size)
        r.font.bold = bold
        r.font.italic = italic
        if color:
            r.font.color.rgb = RGBColor(*color)
    return p

def H1(text):
    return P(text, size=14, bold=True, before=14, after=8)

def H2(text):
    return P(text, size=12, bold=True, before=10, after=6)

def body(text, indent=True):
    p = P(text, align=WD_ALIGN_PARAGRAPH.JUSTIFY, after=6)
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.0)
    return p

def li(lead, rest=""):
    p = P(align=WD_ALIGN_PARAGRAPH.JUSTIFY, after=4)
    p.paragraph_format.left_indent = Cm(0.63)
    p.paragraph_format.first_line_indent = Cm(-0.63)
    r = p.add_run(lead)
    r.font.name = "Times New Roman"; r.font.size = Pt(12); r.font.bold = True
    if rest:
        r2 = p.add_run(rest)
        r2.font.name = "Times New Roman"; r2.font.size = Pt(12)
    return p

def caption(text):
    return P(text, align=WD_ALIGN_PARAGRAPH.CENTER, size=12, bold=True, before=6, after=12)

def set_cell(cell, text, bold=False, size=10, align=WD_ALIGN_PARAGRAPH.LEFT):
    cell.text = ""
    p = cell.paragraphs[0]
    p.alignment = align
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.space_before = Pt(2)
    r = p.add_run(text)
    r.font.name = "Times New Roman"; r.font.size = Pt(size); r.font.bold = bold

def add_table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        set_cell(t.rows[0].cells[i], h, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            set_cell(cells[i], v)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    return t

def pic(path, width_cm=None, height_cm=None, page_break=False):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if page_break:
        p.paragraph_format.page_break_before = True
    kw = {}
    if width_cm:
        kw["width"] = Cm(width_cm)
    if height_cm:
        kw["height"] = Cm(height_cm)
    p.add_run().add_picture(path, **kw)
    return p

