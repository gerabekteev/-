// ---------- Сборка DI ----------
const POOLS = ['P_client', 'P_so', 'P_om', 'P_kadr', 'P_dir', 'P_buh', 'P_sup'];
const LANES = ['L1', 'L2', 'L3', 'L4', 'L5', 'L6'];

let di = '';
for (const id of POOLS) {
  const [x, y, w, h] = shapes[id];
  di += `      <bpmndi:BPMNShape id="${id}_di" bpmnElement="${id}" isHorizontal="true">\n        <dc:Bounds x="${x}" y="${y}" width="${w}" height="${h}" />\n      </bpmndi:BPMNShape>\n`;
}
for (const id of LANES) {
  const [x, y, w, h] = shapes[id];
  di += `      <bpmndi:BPMNShape id="${id}_di" bpmnElement="${id}" isHorizontal="true">\n        <dc:Bounds x="${x}" y="${y}" width="${w}" height="${h}" />\n      </bpmndi:BPMNShape>\n`;
}
for (const [id, [x, y, w, h]] of Object.entries(shapes)) {
  if (POOLS.includes(id) || LANES.includes(id)) continue;
  di += `      <bpmndi:BPMNShape id="${id}_di" bpmnElement="${id}">\n        <dc:Bounds x="${x}" y="${y}" width="${w}" height="${h}" />\n      </bpmndi:BPMNShape>\n`;
}
for (const [id, pts] of Object.entries(W)) {
  const wp = pts.map(([x, y]) => `        <di:waypoint x="${x}" y="${y}" />`).join('\n');
  di += `      <bpmndi:BPMNEdge id="${id}_di" bpmnElement="${id}">\n${wp}\n      </bpmndi:BPMNEdge>\n`;
}

const src = readFileSync('diagram_src.bpmn', 'utf-8');
const out = src.replace('</bpmn:definitions>',
  `  <bpmndi:BPMNDiagram id="Diagram_1">\n    <bpmndi:BPMNPlane id="Plane_1" bpmnElement="Collab_1">\n${di}    </bpmndi:BPMNPlane>\n  </bpmndi:BPMNDiagram>\n</bpmn:definitions>`);
writeFileSync('prommash_kak_dolzhno_byt.bpmn', out);
